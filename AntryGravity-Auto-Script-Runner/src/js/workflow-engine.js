/**
 * workflow-engine.js (Workflow Engine & Auto Script Generator)
 * ────────────────────────────────────────────────────────────
 * The centerpiece of AntryGravity Auto Script Runner.
 * 
 * Features:
 *  - Interactive multi-step automation builder (Add, Remove, Reorder, Enable/Disable)
 *  - Combines Photoshop Actions, JSX/UXP scripts, and built-in modules
 *  - Generates ready-to-run UXP / ExtendScript code preview
 *  - Executes complete multi-step pipeline on single docs or through the batch queue
 */

'use strict';

const AGWorkflowEngine = (() => {

  const STEP_TYPES = {
    UPSCALE:    { id: 'upscale',    label: 'AI Upscale',          icon: '🔍' },
    GRAIN:      { id: 'grain',      label: 'Apply Film Grain',    icon: '✨' },
    GRADIENT:   { id: 'gradient',   label: 'Apply Gradient',      icon: '🌈' },
    BLUR:       { id: 'blur',       label: 'Apply Blur',          icon: '💧' },
    ACTION:     { id: 'action',     label: 'Run Action',          icon: '⚡' },
    SCRIPT:     { id: 'script',     label: 'Run Script',          icon: '📜' },
    BACKGROUND: { id: 'background', label: 'Remove Background',   icon: '✂️' },
    PASSPORT:   { id: 'passport',   label: 'Passport Photo Grid', icon: '👤' },
    RESIZE:     { id: 'resize',     label: 'Smart Resize',        icon: '📐' },
    EFFECTS:    { id: 'effects',    label: 'Advanced Effect',     icon: '🎨' },
    EXPORT:     { id: 'export',     label: 'Export Document',     icon: '💾' }
  };

  let _steps = [
    { id: 'step_1', type: 'upscale',    enabled: true, label: 'Upscale 4K',       options: { targetWidth: 3840, targetHeight: 2160, sharpen: true } },
    { id: 'step_2', type: 'grain',      enabled: true, label: 'Medium Film Grain', options: { preset: 'Medium Grain', amount: 12, monochromatic: true } },
    { id: 'step_3', type: 'resize',     enabled: true, label: 'Smart Resize DPI',  options: { dpi: 300 } },
    { id: 'step_4', type: 'export',     enabled: true, label: 'Save as JPEG',     options: { format: 'jpg', quality: 11, suffix: '_PROCESSED' } }
  ];

  let _listeners = [];

  function _emit(event, data) {
    _listeners.forEach(fn => { try { fn(event, data); } catch (e) {} });
  }

  /**
   * Generates a runnable automation script representation of the workflow.
   */
  function generateWorkflowScript(mode = 'uxp') {
    const activeSteps = _steps.filter(s => s.enabled);
    const dateStr = new Date().toISOString();

    if (mode === 'uxp') {
      let code = `/**\n * Auto-generated by AntryGravity Auto Script Runner (UXP)\n * Generated: ${dateStr}\n */\n\n`;
      code += `const { app, core, action, constants } = require('photoshop');\n\n`;
      code += `async function runWorkflow() {\n`;
      code += `  await core.executeAsModal(async () => {\n`;
      code += `    const doc = app.activeDocument;\n`;
      code += `    if (!doc) throw new Error("No active document open");\n\n`;

      activeSteps.forEach((s, idx) => {
        code += `    // Step ${idx + 1}: ${s.label}\n`;
        switch (s.type) {
          case 'upscale':
            code += `    await action.batchPlay([{\n`;
            code += `      _obj: "imageSize",\n`;
            code += `      width: { _unit: "pixelsUnit", _value: ${s.options.targetWidth || 3840} },\n`;
            code += `      height: { _unit: "pixelsUnit", _value: ${s.options.targetHeight || 2160} },\n`;
            code += `      interfaceIconFrameDimmed: { _enum: "interpolationType", _value: "preserveDetailsUpscale" }\n`;
            code += `    }], {});\n\n`;
            break;
          case 'grain':
            code += `    await action.batchPlay([{\n`;
            code += `      _obj: "addNoise",\n`;
            code += `      noise: { _unit: "percentUnit", _value: ${s.options.amount || 10} },\n`;
            code += `      distribution: { _enum: "distribution", _value: "gaussian" },\n`;
            code += `      monochromatic: ${!!s.options.monochromatic}\n`;
            code += `    }], {});\n\n`;
            break;
          case 'blur':
            code += `    await action.batchPlay([{\n`;
            code += `      _obj: "gaussianBlur",\n`;
            code += `      radius: { _unit: "pixelsUnit", _value: ${s.options.radius || 5} }\n`;
            code += `    }], {});\n\n`;
            break;
          case 'action':
            code += `    await action.batchPlay([{\n`;
            code += `      _obj: "play",\n`;
            code += `      _target: [{ _ref: "action", _name: "${s.options.actionName || 'Vignette'}" }],\n`;
            code += `      from: { _ref: "actionSet", _name: "${s.options.actionSet || 'Default Actions'}" }\n`;
            code += `    }], {});\n\n`;
            break;
          case 'resize':
            code += `    await action.batchPlay([{\n`;
            code += `      _obj: "imageSize",\n`;
            code += `      resolution: { _unit: "densityUnit", _value: ${s.options.dpi || 300} }\n`;
            code += `    }], {});\n\n`;
            break;
          default:
            code += `    // Custom operation: ${s.type}\n\n`;
            break;
        }
      });

      code += `  }, { commandName: "AntryGravity Automated Workflow" });\n`;
      code += `}\n\nrunWorkflow();\n`;
      return code;
    } else {
      // ExtendScript JSX mode
      let code = `/**\n * Auto-generated by AntryGravity Auto Script Runner (JSX)\n * Generated: ${dateStr}\n */\n\n`;
      code += `(function() {\n`;
      code += `  if (app.documents.length === 0) return;\n`;
      code += `  var doc = app.activeDocument;\n\n`;

      activeSteps.forEach((s, idx) => {
        code += `  // Step ${idx + 1}: ${s.label}\n`;
        if (s.type === 'grain') {
          code += `  doc.activeLayer.applyAddNoise(${s.options.amount || 10}, NoiseDistribution.GAUSSIAN, true);\n`;
        } else if (s.type === 'blur') {
          code += `  doc.activeLayer.applyGaussianBlur(${s.options.radius || 5});\n`;
        } else if (s.type === 'action') {
          code += `  app.doAction("${s.options.actionName || 'Action'}", "${s.options.actionSet || 'Set'}");\n`;
        } else if (s.type === 'resize') {
          code += `  doc.resizeImage(null, null, ${s.options.dpi || 300}, ResampleMethod.NONE);\n`;
        }
      });

      code += `})();\n`;
      return code;
    }
  }

  /**
   * Executes a single step against the active Photoshop document.
   */
  async function _executeStep(step, bridge) {
    if (!step.enabled) return;
    AGLogger.info(`[WorkflowEngine] Running Step: ${step.label} (${step.type})`);

    switch (step.type) {
      case 'upscale':
        if (window.UpscaleManager) {
          await window.UpscaleManager.upscale(step.options);
        } else {
          await bridge.resizeImage(step.options.targetWidth || 3840, step.options.targetHeight || 2160);
        }
        break;

      case 'grain':
        if (window.AGGrainModule) {
          await window.AGGrainModule.applyGrain(step.options);
        } else {
          await bridge.addNoise(step.options.amount || 10, 'gaussian', true);
        }
        break;

      case 'gradient':
        if (window.AGGradientModule) {
          await window.AGGradientModule.applyGradient(step.options);
        } else {
          await bridge.applyGradientFill('#6c63ff', '#00c8ff');
        }
        break;

      case 'blur':
        if (window.AGBlurModule) {
          await window.AGBlurModule.applyBlur(step.options);
        } else {
          await bridge.gaussianBlur(step.options.radius || 4);
        }
        break;

      case 'action':
        await bridge.runAction(step.options.actionSet, step.options.actionName);
        break;

      case 'script':
        if (step.options.scriptId && window.AGScriptRunner) {
          await window.AGScriptRunner.executeScript(step.options.scriptId, true);
        }
        break;

      case 'background':
        if (window.BackgroundRemovalManager) {
          await window.BackgroundRemovalManager.removeBackground(step.options);
        }
        break;

      case 'passport':
        if (window.AGPassportModule) {
          await window.AGPassportModule.generatePassport(step.options);
        }
        break;

      case 'resize':
        if (window.AGResizeModule) {
          await window.AGResizeModule.applyResize(step.options);
        } else {
          if (step.options.dpi) await bridge.setResolution(step.options.dpi);
        }
        break;

      case 'effects':
        if (window.AGEffectsModule) {
          await window.AGEffectsModule.applyEffect(step.options.effectKey || 'glow');
        }
        break;

      case 'export':
        // Export is handled as final step or via ExportManager
        break;

      default:
        AGLogger.warn(`[WorkflowEngine] Unknown step type: ${step.type}`);
        break;
    }
  }

  return {
    STEP_TYPES,

    getSteps() {
      return [..._steps];
    },

    setSteps(newSteps) {
      _steps = [...newSteps];
      _emit('change', _steps);
    },

    addStep(type, label = '', options = {}) {
      const typeDef = STEP_TYPES[type.toUpperCase()] || { label: type, icon: '⚙️' };
      const step = {
        id: `step_${Date.now()}_${Math.random().toString(36).substr(2, 4)}`,
        type,
        enabled: true,
        label: label || typeDef.label,
        options
      };
      _steps.push(step);
      AGLogger.info(`[WorkflowEngine] Added step: ${step.label}`);
      _emit('change', _steps);
      return step;
    },

    removeStep(id) {
      const idx = _steps.findIndex(s => s.id === id);
      if (idx !== -1) {
        const removed = _steps.splice(idx, 1)[0];
        AGLogger.info(`[WorkflowEngine] Removed step: ${removed.label}`);
        _emit('change', _steps);
        return true;
      }
      return false;
    },

    toggleStep(id) {
      const step = _steps.find(s => s.id === id);
      if (step) {
        step.enabled = !step.enabled;
        _emit('change', _steps);
        return step.enabled;
      }
      return false;
    },

    moveStep(fromIndex, toIndex) {
      if (fromIndex < 0 || fromIndex >= _steps.length || toIndex < 0 || toIndex >= _steps.length) return;
      const [item] = _steps.splice(fromIndex, 1);
      _steps.splice(toIndex, 0, item);
      _emit('change', _steps);
    },

    duplicateStep(id) {
      const idx = _steps.findIndex(s => s.id === id);
      if (idx !== -1) {
        const orig = _steps[idx];
        const copy = {
          ...JSON.parse(JSON.stringify(orig)),
          id: `step_${Date.now()}_copy`,
          label: `${orig.label} (Copy)`
        };
        _steps.splice(idx + 1, 0, copy);
        _emit('change', _steps);
        return copy;
      }
      return null;
    },

    generateScript: generateWorkflowScript,

    /**
     * Executes the workflow on the active document or runs batch queue
     */
    async runOnActiveDocument() {
      const bridge = (window.AGApp && window.AGApp.getActiveBridge ? window.AGApp.getActiveBridge() : (window.PSAdapter || window.CEPAdapter || window.WebStudioAdapter));
      if (!bridge) throw new Error('No Photoshop bridge connected.');

      const activeSteps = _steps.filter(s => s.enabled);
      if (activeSteps.length === 0) {
        AGLogger.warn('[WorkflowEngine] No active steps in workflow');
        return;
      }

      AGLogger.info(`[WorkflowEngine] Executing ${activeSteps.length} steps on active document...`);
      const startTime = performance.now();

      for (let i = 0; i < activeSteps.length; i++) {
        await _executeStep(activeSteps[i], bridge);
      }

      // If an export step exists, trigger export
      const exportStep = activeSteps.find(s => s.type === 'export');
      if (exportStep && window.AGExportManager) {
        await window.AGExportManager.exportActiveDocument('workflow_result');
      }

      const totalTime = ((performance.now() - startTime) / 1000).toFixed(2);
      AGLogger.success(`[WorkflowEngine] Workflow completed successfully in ${totalTime}s!`);
    },

    /**
     * Executes the full workflow across the batch queue
     */
    async runOnBatchQueue() {
      if (!window.AGQueue) throw new Error('Queue engine not initialized');

      const items = window.AGQueue.getItems();
      if (items.length === 0) {
        throw new Error('Batch Queue is empty. Add images first.');
      }

      const activeSteps = _steps.filter(s => s.enabled);
      if (activeSteps.length === 0) {
        throw new Error('Workflow has no active steps enabled.');
      }

      AGLogger.info(`[WorkflowEngine] Starting batch workflow run for ${items.length} images...`);

      window.AGQueue.setProcessor(async (item, index) => {
        const bridge = (window.AGApp && window.AGApp.getActiveBridge ? window.AGApp.getActiveBridge() : (window.PSAdapter || window.CEPAdapter || window.WebStudioAdapter));

        // Open image
        if (item.entry && bridge.openDocument) {
          await bridge.openDocument(item.entry);
        } else if (item.file && bridge.openDocument) {
          await bridge.openDocument(item.file);
        } else if (item.path && bridge.openDocument) {
          await bridge.openDocument(item.path);
        }

        // Run each active step sequentially
        for (let i = 0; i < activeSteps.length; i++) {
          await _executeStep(activeSteps[i], bridge);
        }

        // Export result
        if (window.AGExportManager) {
          await window.AGExportManager.exportActiveDocument(item.name, index);
        } else {
          await bridge.closeDocument('saveChanges');
        }
      });

      window.AGQueue.start();
    },

    on(fn) { _listeners.push(fn); }
  };
})();

window.AGWorkflowEngine = AGWorkflowEngine;
